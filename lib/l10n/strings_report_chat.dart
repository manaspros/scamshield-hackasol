String rc(String lang, String key, [Map<String, Object> args = const {}]) {
  var s = reportChatStrings(lang, key);
  for (final e in args.entries) {
    s = s.replaceAll('{${e.key}}', '${e.value}');
  }
  return s;
}

/// Persona variant if one exists, else the plain key.
String rcFor(String lang, String key, String? variant, [Map<String, Object> args = const {}]) {
  if (variant != null) {
    final k = '${key}_$variant';
    final v = reportChatStrings(lang, k);
    if (v != k) return rc(lang, k, args);
  }
  return rc(lang, key, args);
}
